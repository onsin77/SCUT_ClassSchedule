function wk(spec) {
    const out = [];
    String(spec).split(',').forEach(seg => {
        seg = seg.trim();
        if (!seg) return;
        const odd = /单/.test(seg), even = /双/.test(seg);
        const ns = seg.match(/\d+/g);
        if (!ns) return;
        const a = +ns[0], b = ns.length > 1 ? +ns[1] : a;
        for (let w = a; w <= b; w++) {
            if (even && w % 2) continue;
            if (odd && !(w % 2)) continue;
            out.push(w);
        }
    });
    return out;
}

