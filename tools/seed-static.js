function compact(weeks) {
    const s = weeks.slice().sort((a, b) => a - b), out = [];
    let i = 0;
    while (i < s.length) {
        let j = i;
        while (j + 1 < s.length && s[j + 1] === s[j] + 1) j++;
        out.push(i === j ? String(s[i]) : s[i] + '-' + s[j]);
        i = j + 1;
    }
    return out.join(',');
}

